    <h1>Acerca de La Canasta</h1>
    <p><strong>Grupo 1 - La Canasta</strong> es un sistema de gestión web para el Torneo Navideño de Básquetbol, desarrollado como proyecto académico de Programación Web.</p>

    <h2 class="h4 mt-4">Descripción del proyecto</h2>
    <p>La aplicación permite administrar los equipos, jugadores, anotaciones y reportes estadísticos del torneo. Sus principales funcionalidades son:</p>
    <ul>
        <li>Gestión de equipos, incluyendo carga de logo.</li>
        <li>Gestión de jugadores, incluyendo fotografía y asignación a un equipo.</li>
        <li>Registro de tiros y puntuaciones por jornada.</li>
        <li>Reportes: lista general de jugadores, jugadores por equipo y máximos anotadores.</li>
        <li>Ficha individual del jugador con su perfil y estadísticas.</li>
    </ul>

    <h2 class="h4 mt-4">Herramientas y tecnologías utilizadas</h2>
    <ul>
        <li>Framework: <strong>Yii 2 Framework</strong> (versión 2.0.55).</li>
        <li>Lenguaje: <strong>PHP 8.x</strong>.</li>
        <li>Base de datos: <strong>MySQL / MariaDB</strong>.</li>
        <li>Servidor web local: <strong>XAMPP</strong> (Apache + MySQL).</li>
        <li>Frontend: <strong>Bootstrap 5</strong> (yii2-bootstrap5).</li>
        <li>Gestor de dependencias: <strong>Composer</strong>.</li>
        <li>Librerías adicionales de Yii 2: YiiAsset, BootstrapAsset, BootstrapPluginAsset, Gii y Debug.</li>
    </ul>

